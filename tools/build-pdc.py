#!/usr/bin/env python3
"""Build pdc.js from PDC_Master.xlsx - the PDC companies on the website.

PDC companies are not stocked: their products are listed so buyers can find
them, and SNT procures and supplies when an order comes in. They show on
search.html under one "PDC Companies" tab (with a company picker), and the
salt finder searches them too.

PDC_Master.xlsx sits next to Master_File.xlsx and uses the SAME columns:

    Company | PRODUCTS | PACK | Composition | In Boxes | Shipper Qty | PTS | MRP | Remark

PTS: leave it blank, NA or 0 - the site shows "NA" for every PDC product.
Photos: put them in the same Photos/ folder, named after the product exactly
as for the main catalogue (photo-namer.html), and they show the same way.

Run from the website folder after changing PDC_Master.xlsx or adding photos:

    python tools/build-pdc.py

This does not touch data.js; convert.py still builds that from Master_File.xlsx.
A company that is already in data.js is refused here, so a product never shows
under both a stocked division and PDC.
"""

import json
import os
import re
import sys
from datetime import datetime

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
from convert import read_rows, read_photos, photo_key  # noqa: E402  same rules as data.js

SOURCE = os.path.join(ROOT, "PDC_Master.xlsx")
TARGET = os.path.join(ROOT, "pdc.js")
DATA_JS = os.path.join(ROOT, "data.js")
RULE = "-" * 68


def stocked_companies():
    """Company names already on the site, read from data.js."""
    try:
        text = open(DATA_JS, encoding="utf-8").read()
    except OSError:
        return set()
    m = re.search(r"companies:\s*(\[.*?\])", text, re.S)
    return {c.lower() for c in json.loads(m.group(1))} if m else set()


def main():
    if not os.path.exists(SOURCE):
        sys.exit(f"PDC_Master.xlsx not found -> {SOURCE}")

    records, issues = read_rows(SOURCE)
    photo_map, _, _ = read_photos(os.path.join(ROOT, "Photos"))

    stocked = stocked_companies()
    clash = sorted({r["company"] for r in records if r["company"].lower() in stocked})
    records = [r for r in records if r["company"] not in clash]
    for r in records:
        r["photo"] = photo_map.get(photo_key(r["product"]))

    # A-Z by product within each company (companies keep sheet order).
    # Numbers sort by value, so "MAXTOL-5" comes before "MAXTOL-10".
    def natural(name):
        return [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", name.lower())]
    co_order = {c: i for i, c in enumerate(dict.fromkeys(r["company"] for r in records))}
    records.sort(key=lambda r: (co_order[r["company"]], natural(r["product"])))

    companies = list(dict.fromkeys(r["company"] for r in records))
    payload = [{
        "company": r["company"], "product": r["product"], "pack": r["pack"],
        "composition": r["composition"], "inBoxes": r["inBoxes"],
        "shipperQty": r["shipperQty"],
        "pts": None,          # PDC rates are not published - shown as NA
        "mrp": r["mrp"], "remark": r["remark"], "photo": r["photo"],
    } for r in records]

    updated_at = datetime.now().strftime("%d %b %Y, %I:%M %p")
    js = (
        "// Auto-generated by tools/build-pdc.py from PDC_Master.xlsx - DO NOT EDIT MANUALLY\n"
        f"// Last updated: {updated_at}\n\n"
        f"const PDC_DATA = {json.dumps(payload, indent=2, ensure_ascii=False)};\n\n"
        "const PDC_META = {\n"
        f'  updatedAt: "{updated_at}",\n'
        f"  totalProducts: {len(payload)},\n"
        f"  companies: {json.dumps(companies, ensure_ascii=False)}\n"
        "};\n"
    )
    tmp = TARGET + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(js)
    os.replace(tmp, TARGET)

    print(RULE)
    print(f"  PDC        {len(payload)} products, {len(companies)} companies, "
          f"{sum(1 for r in records if r['photo'])} with photos")
    for i, co in enumerate(companies, 1):
        print(f"     {i:>2}. {co:<30}{sum(1 for r in records if r['company'] == co):>5}")
    errors = [i for i in issues if i[0] == "error"]
    if clash or errors:
        print(RULE)
        print("  NEEDS FIXING")
        for co in clash:
            print(f"     '{co}' is already a stocked company in data.js - skipped")
        for _, _, where, msg in errors:
            print(f"     row {where.split('!')[-1]:<6}{msg}")
    dups = [i for i in issues if i[1] == "duplicate-row"]
    if dups:
        print(f"  Duplicate rows skipped: {len(dups)}")
    print(RULE)
    print(f"  Written    pdc.js")
    print(RULE)


if __name__ == "__main__":
    main()
